// Bundles @xmldom/xmldom (CommonJS, 6 files) into ONE self-contained JS string
// that sets `globalThis.xmldom = { DOMParser, XMLSerializer, DOMImplementation }`.
//
// This bundle is embedded into index.html and prepended to the Web Worker
// source, because Web Workers have no native DOMParser. Pure JS, no Node
// globals, worker-safe. Re-run after bumping @xmldom: `node tools/bundle-xmldom.mjs`.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve('node_modules/@xmldom/xmldom/lib');
// Dependency order is irrelevant (the tiny CJS loader resolves recursively),
// but every module that is require()'d must be present here.
const modules = ['conventions', 'sax', 'entities', 'dom', 'dom-parser', 'index'];

const src = {};
for (const m of modules) src[m] = fs.readFileSync(path.join(root, m + '.js'), 'utf8');

// Wrap each module as a function factory (module, exports, require) and store
// its source as a JSON string so backticks/`${}` in @xmldom can't break us.
const factories = modules.map(m => `${JSON.stringify(m)}: new Function("module","exports","require", ${JSON.stringify(src[m])})`).join(',\n  ');

const bundle = `/* @xmldom/xmldom bundle — generated by tools/bundle-xmldom.mjs. Sets globalThis.xmldom. */
(function () {
  var __mods = {
  ${factories}
  };
  var __cache = {};
  function __req(name) {
    name = name.replace(/^\\.\\//, "");
    if (__cache[name]) return __cache[name].exports;
    var m = { exports: {} };
    __cache[name] = m;
    __mods[name](m, m.exports, function (n) { return __req(n); });
    return m.exports;
  }
  var m = { exports: {} };
  __mods.index(m, m.exports, function (n) { return __req(n); });
  globalThis.xmldom = m.exports;
})();
`;

fs.mkdirSync('tools', { recursive: true });
fs.writeFileSync('xmldom.bundle.js', bundle);
console.log('wrote xmldom.bundle.js:', bundle.length, 'bytes');
console.log('modules:', modules.join(', '));
